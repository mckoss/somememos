// Builds the one-file CLI (IMPLEMENTATION.md task 4.1): bundle/somememos.mjs,
// a single self-contained ES module with the CLI and its workspace packages
// (core, sqlite-store), compiled from their TypeScript sources. It needs only
// Node >= 22.13 (the CLI's minimum; building it needs Node 26, like the rest of
// the repository): Node built-ins (node:sqlite among them) stay imports, and
// there are no other dependencies and no native modules.
//
// The version is read from the root package.json at build time (the single
// source of truth), replacing core's generated version module, so the bundle
// is right even when that generated file is stale.
//
//   npm run bundle -w @somememos/cli
//   node packages/cli/scripts/bundle.mjs --out /tmp/somememos.mjs

import { chmodSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { builtinModules } from 'node:module';
import { dirname, join, resolve, sep } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import { build } from 'rolldown';

const here = dirname(fileURLToPath(import.meta.url));
const pkgDir = join(here, '..');
const rootPkg = JSON.parse(readFileSync(join(pkgDir, '..', '..', 'package.json'), 'utf8'));
const version = rootPkg.version;
if (typeof version !== 'string' || !/^\d+\.\d+\.\d+/.test(version)) {
  throw new Error('the root package.json has no valid version');
}
// `--out <file>` builds elsewhere (the bundle test builds into a temp dir).
const outArg = process.argv.indexOf('--out');
const outFile =
  outArg > 0 ? resolve(process.argv[outArg + 1] ?? '') : join(pkgDir, 'bundle', 'somememos.mjs');
const builtins = new Set(builtinModules);

/** core/src/version.ts, replaced by the root package.json's version. */
const versionPlugin = {
  name: 'somememos-version',
  load(id) {
    if (id.endsWith(`${sep}core${sep}src${sep}version.ts`)) {
      return `export const VERSION = ${JSON.stringify(version)};\n`;
    }
    return null;
  },
};

await build({
  input: join(pkgDir, 'src', 'main.ts'),
  platform: 'node',
  // Workspace packages resolve to their TypeScript sources.
  resolve: { conditionNames: ['source', 'import', 'node', 'default'] },
  external: (id) => id.startsWith('node:') || builtins.has(id),
  plugins: [versionPlugin],
  output: {
    file: outFile,
    format: 'esm',
    // The bundle is generated code: no lint (it is formatted below, so
    // \`prettier --check .\` passes too).
    banner:
      '#!/usr/bin/env node\n/* eslint-disable */\n// Generated by packages/cli/scripts/bundle.mjs. Do not edit.',
    sourcemap: false,
    minify: false,
  },
  logLevel: 'warn',
});

// Nothing but Node built-ins may remain as imports.
const text = readFileSync(outFile, 'utf8');
const imports = [
  ...text.matchAll(/^import\s+(?:[\w$*{},\s]+\s+from\s+)?["']([^"']+)["'];?$/gm),
  ...text.matchAll(/\bimport\(\s*["']([^"']+)["']\s*\)/g),
].map((m) => m[1]);
const foreign = imports.filter((s) => !s.startsWith('node:') && !builtins.has(s));
if (foreign.length > 0)
  throw new Error(`the bundle imports non-built-in modules: ${foreign.join(', ')}`);
if (!text.includes(JSON.stringify(version))) throw new Error('the bundle lacks the version');
const prettierConfig =
  (await prettier.resolveConfig(join(pkgDir, 'bundle', 'somememos.mjs'))) ?? {};
writeFileSync(outFile, await prettier.format(text, { ...prettierConfig, filepath: outFile }));
chmodSync(outFile, 0o755);
const kib = Math.round(statSync(outFile).size / 1024);
console.log(`bundle: ${outFile} (${kib} KiB, version ${version})`);
